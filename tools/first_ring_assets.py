def png_chunk(kind, content):
    payload = kind + content
    return struct.pack(">I", len(content)) + payload + struct.pack(">I", zlib.crc32(payload))


def generate(directory, assets):
    scale, side = 3, 32
    size = side * scale
    for name, rectangles in SPRITES.items():
        pixels = [bytearray(side * 4) for row in range(side)]
        for left, top, right, bottom, color in rectangles:
            rgba = bytes.fromhex(color) + b"\xff"
            for row in pixels[top:bottom + 1]:
                row[left*4:(right + 1)*4] = rgba * (right - left + 1)
        scanlines = b"".join(
            (b"\x00" + b"".join(row[index:index+4] * scale for index in range(0, len(row), 4))) * scale
            for row in pixels
        )
        filename = f"{name}.png"
        (directory / filename).write_bytes(
            b"\x89PNG\r\n\x1a\n"
            + png_chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + png_chunk(b"IDAT", zlib.compress(scanlines))
            + png_chunk(b"IEND", b"")
        )
        assets[name] = {"file": filename, "width": size, "height": size}


