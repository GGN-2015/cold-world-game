const storageKey = 'cold-world-language-v1';
let language = 'zh';
try {
  if (localStorage.getItem(storageKey) === 'en') language = 'en';
} catch {}

export const getLanguage = () => language;
export const hasTranslation = (key) => Object.hasOwn(messages, key);
export function t(key, parameters = {}) {
  const message = messages[key]?.[language === 'en' ? 1 : 0] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) => String(parameters[name] ?? match));
}

export function translatePage() {
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
  document.title = t('page.title');
  document.querySelector('meta[name="description"]').content = t('page.description');
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll('[data-i18n-html]')) node.innerHTML = t(node.dataset.i18nHtml);
  for (const attribute of ['title', 'aria-label', 'placeholder', 'alt']) {
    for (const node of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
      node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
    }
  }
  for (const button of document.querySelectorAll('[data-language-toggle]')) {
    button.textContent = language === 'en' ? '中文' : 'EN';
    button.title = t('language.switch');
    button.setAttribute('aria-label', t('language.switch'));
  }
}

export function setLanguage(next) {
  if (!['zh', 'en'].includes(next) || next === language) return;
  language = next;
  try { localStorage.setItem(storageKey, language); } catch {}
  translatePage();
  window.dispatchEvent(new Event('cold-world-languagechange'));
}

export function initializeLanguage() {
  translatePage();
  for (const button of document.querySelectorAll('[data-language-toggle]')) {
    button.addEventListener('click', () => setLanguage(language === 'en' ? 'zh' : 'en'));
  }
}
